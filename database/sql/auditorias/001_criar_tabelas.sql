CREATE TABLE CONECTA_AUD_NISA (
  NR_SEQUENCIA NUMBER NOT NULL, IE_TIPO_AUDITORIA VARCHAR2(30) NOT NULL, DT_AUDITORIA DATE NOT NULL,
  CD_SETOR_ATENDIMENTO NUMBER NOT NULL, NM_SETOR VARCHAR2(255) NOT NULL, CD_AVALIADOR NUMBER NOT NULL,
  NM_AVALIADOR VARCHAR2(255) NOT NULL, IE_TURNO VARCHAR2(1) NOT NULL, DS_OBSERVACAO VARCHAR2(4000),
  NM_USUARIO VARCHAR2(100) NOT NULL, DT_CRIACAO DATE DEFAULT SYSDATE NOT NULL,
  DT_ATUALIZACAO DATE DEFAULT SYSDATE NOT NULL, IE_SITUACAO VARCHAR2(1) DEFAULT 'A' NOT NULL,
  CONSTRAINT PK_CON_AUD_NISA PRIMARY KEY (NR_SEQUENCIA),
  CONSTRAINT CK_CON_AUD_NISA_TIPO CHECK (IE_TIPO_AUDITORIA IN ('HIGIENE_MAOS')),
  CONSTRAINT CK_CON_AUD_NISA_TURNO CHECK (IE_TURNO IN ('D', 'N')),
  CONSTRAINT CK_CON_AUD_NISA_SIT CHECK (IE_SITUACAO IN ('A', 'I'))
);

CREATE TABLE CONECTA_AUD_NISA_PROF (
  NR_SEQUENCIA NUMBER NOT NULL, NR_SEQ_AUDITORIA NUMBER NOT NULL, CD_PESSOA_FISICA NUMBER NOT NULL,
  NM_PROFISSIONAL VARCHAR2(255) NOT NULL, DT_CRIACAO DATE DEFAULT SYSDATE NOT NULL,
  DT_ATUALIZACAO DATE DEFAULT SYSDATE NOT NULL, IE_SITUACAO VARCHAR2(1) DEFAULT 'A' NOT NULL,
  CONSTRAINT PK_CON_AUD_NISA_PROF PRIMARY KEY (NR_SEQUENCIA),
  CONSTRAINT FK_CON_AUD_NISA_PROF FOREIGN KEY (NR_SEQ_AUDITORIA) REFERENCES CONECTA_AUD_NISA (NR_SEQUENCIA),
  CONSTRAINT CK_CON_AUD_NISA_PROF_S CHECK (IE_SITUACAO IN ('A', 'I'))
);

CREATE TABLE CONECTA_AUD_NISA_OPORT (
  NR_SEQUENCIA NUMBER NOT NULL, NR_SEQ_AUDITORIA_PROFISSIONAL NUMBER NOT NULL,
  IE_TIPO_OPORTUNIDADE VARCHAR2(40) NOT NULL, IE_RESULTADO VARCHAR2(1) NOT NULL,
  DT_CRIACAO DATE DEFAULT SYSDATE NOT NULL, DT_ATUALIZACAO DATE DEFAULT SYSDATE NOT NULL,
  IE_SITUACAO VARCHAR2(1) DEFAULT 'A' NOT NULL,
  CONSTRAINT PK_CON_AUD_NISA_OPORT PRIMARY KEY (NR_SEQUENCIA),
  CONSTRAINT FK_CON_AUD_NISA_OPORT FOREIGN KEY (NR_SEQ_AUDITORIA_PROFISSIONAL) REFERENCES CONECTA_AUD_NISA_PROF (NR_SEQUENCIA),
  CONSTRAINT UQ_CON_AUD_NISA_OPORT UNIQUE (NR_SEQ_AUDITORIA_PROFISSIONAL, IE_TIPO_OPORTUNIDADE),
  CONSTRAINT CK_CON_AUD_NISA_OP_T CHECK (IE_TIPO_OPORTUNIDADE IN ('ANTES_CONTATO_PACIENTE', 'ANTES_PROCEDIMENTO_ASSEPTICO', 'APOS_FLUIDOS', 'APOS_CONTATO_PACIENTE', 'APOS_CONTATO_AMBIENTE')),
  CONSTRAINT CK_CON_AUD_NISA_OP_R CHECK (IE_RESULTADO IN ('A', 'S', 'P')),
  CONSTRAINT CK_CON_AUD_NISA_OP_S CHECK (IE_SITUACAO IN ('A', 'I'))
);
